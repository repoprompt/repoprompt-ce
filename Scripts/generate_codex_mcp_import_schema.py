#!/usr/bin/env python3
"""Project the pinned upstream MCP config schema into the app (no runtime resource IO).

The fixture contains RawMcpServerConfig's transitive definitions from the official
config.schema.json at the Vendor/Codex pin; only descriptions/defaults are removed.
Update the fixture from that pinned upstream schema when updating Codex.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'Sources/RepoPrompt/Infrastructure/AI/Providers/Codex/AppOnly/CodexUserMCPSchema.swift'


def check_or_generate(check: bool = True) -> None:
    fixture = json.loads((ROOT / 'Scripts/Fixtures/codex-mcp-import-schema.json').read_text())
    manifest = json.loads((ROOT / 'Vendor/Codex/manifest.json').read_text())
    if fixture['codexVersion'] != manifest['version']:
        raise ValueError('MCP import schema must be updated with the bundled Codex pin')
    # Chunk at definition boundaries to keep generated source readable and formatter-bounded.
    lines = json.dumps(fixture['definitions'], indent=2, sort_keys=True).splitlines()
    body = '\n'.join('        ' + line for line in lines)
    generated = ('// Generated by Scripts/generate_codex_mcp_import_schema.py; do not edit.\n'
                 '// Source: ' + fixture['source'] + '\n'
                 'import Foundation\n\n'
                 'enum CodexUserMCPSchema {\n'
                 '    static var definitions: [String: Any] {\n'
                 '        let json = #"""\n' + body + '\n'
                 '        """#\n'
                 '        return (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [String: Any] ?? [:]\n'
                 '    }\n}\n')
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise ValueError('MCP schema projection is stale; run Scripts/generate_codex_mcp_import_schema.py')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    check_or_generate(args.check)
